#!/usr/bin/env python3
"""Embed a binary file as a C++ header (byte array)."""
import sys


def main():
    src, dst = sys.argv[1], sys.argv[2]
    data = open(src, "rb").read()
    with open(dst, "w") as f:
        f.write("// generated by tools/embed.py - do not edit\n")
        f.write("#include <cstdint>\n#include <cstddef>\nnamespace embed {\n")
        f.write("const uint8_t libdaproxy_so[] = {")
        for i in range(0, len(data), 24):
            f.write("\n" + ",".join(str(b) for b in data[i : i + 24]) + ",")
        f.write("\n};\n")
        f.write("const size_t libdaproxy_so_len = sizeof(libdaproxy_so);\n}\n")


if __name__ == "__main__":
    main()
